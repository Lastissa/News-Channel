"""Traffic-source classification used by the analytics buffers.

The Referer header is the primary signal: browsers and search engines send it
on ordinary navigations, and it survives even when a sharing app strips our
UTM parameters. ``utm_source`` is only a fallback for requests that arrive
without a referrer (or with an unrecognised one).

Keys are deliberately short: AdvertEvent.source is a 16-character column and
the same keys are stored on StoryView.source. Labels live here so every screen
uses the same wording.
"""

from __future__ import annotations

import re
from urllib.parse import parse_qs, parse_qsl, urlencode, urlsplit, urlunsplit

from django.conf import settings

SOURCE_GOOGLE = "google"
SOURCE_GOOGLE_NAME = "google_name"
SOURCE_GOOGLE_NAME_ABUREPORT = "google_abu"
SOURCE_FACEBOOK = "facebook"
SOURCE_WHATSAPP = "whatsapp"
SOURCE_X = "x_twitter"
SOURCE_INSTAGRAM = "instagram"
SOURCE_LINKEDIN = "linkedin"
SOURCE_BING = "bing"
SOURCE_ABUREPORT = "abureport"
SOURCE_DIRECT = "direct"
SOURCE_OTHER = "other"

#   ``{name}`` is filled in by the caller when rendering an author's panel.
SOURCE_LABELS = {
    SOURCE_GOOGLE: "Google",
    SOURCE_GOOGLE_NAME: "Google: {name}",
    SOURCE_GOOGLE_NAME_ABUREPORT: "Google: {name} abureport",
    SOURCE_FACEBOOK: "Facebook",
    SOURCE_WHATSAPP: "WhatsApp",
    SOURCE_X: "X / Twitter",
    SOURCE_INSTAGRAM: "Instagram",
    SOURCE_LINKEDIN: "LinkedIn",
    SOURCE_BING: "Bing",
    SOURCE_ABUREPORT: "Abureport",
    SOURCE_DIRECT: "Direct",
    SOURCE_OTHER: "Other",
}

#   Kept in display order, so an analytics panel can iterate this instead of
#   inventing its own ordering.
SOURCE_ORDER = (
    SOURCE_GOOGLE,
    SOURCE_GOOGLE_NAME,
    SOURCE_GOOGLE_NAME_ABUREPORT,
    SOURCE_FACEBOOK,
    SOURCE_WHATSAPP,
    SOURCE_X,
    SOURCE_INSTAGRAM,
    SOURCE_LINKEDIN,
    SOURCE_BING,
    SOURCE_ABUREPORT,
    SOURCE_DIRECT,
    SOURCE_OTHER,
)

_WHITESPACE = re.compile(r"\s+")


def normalize_name(value):
    """Lowercase, whitespace-collapsed name used for the two Google patterns."""
    return _WHITESPACE.sub(" ", (value or "").strip()).lower()


def source_label(key, name=""):
    """Return the display label for a stored source key."""
    template = SOURCE_LABELS.get(key, SOURCE_LABELS[SOURCE_OTHER])
    if "{name}" in template:
        return template.format(name=(name or "author").strip())
    return template


def tag_internal_url(value):
    """Add ``utm_source=abureport`` to a story link generated by this site.

    Relative paths and absolute URLs are both accepted. Existing query values
    and fragments are preserved, and an already tagged link is left alone, so
    the fallback marker never overwrites a deliberate campaign.
    """
    value = (value or "").strip()
    if not value:
        return value
    try:
        parts = urlsplit(value)
    except ValueError:
        return value
    query = parse_qsl(parts.query, keep_blank_values=True)
    if any(key.lower() == "utm_source" for key, _item in query):
        return value
    query.append(("utm_source", SOURCE_ABUREPORT))
    return urlunsplit((parts.scheme, parts.netloc, parts.path, urlencode(query), parts.fragment))


def _host(value):
    host = (value or "").strip().lower().rstrip(".")
    for prefix in ("www.", "m.", "l.", "web.", "mobile."):
        if host.startswith(prefix):
            host = host[len(prefix):]
            break
    return host


def _own_hosts(request):
    hosts = set()
    try:
        hosts.add(_host(request.get_host()))
    except Exception:
        pass
    for value in getattr(settings, "ALLOWED_HOSTS", []) or []:
        value = _host(value)
        if value and "*" not in value:
            hosts.add(value)
    return hosts


def _search_query(referrer):
    try:
        parts = urlsplit(referrer or "")
    except ValueError:
        return ""
    query = parse_qs(parts.query, keep_blank_values=True)
    for key in ("q", "query"):
        values = query.get(key) or []
        if values and values[0]:
            return normalize_name(values[0])
    return ""


def classify_request_source(request, author_name=None):
    """Classify an incoming page view as one of the keys in SOURCE_LABELS.

    ``author_name`` is the target author's full name. It is only used to tell
    the two Google name patterns apart; without it a Google visit stays simply
    "google" instead of being guessed.
    """
    referrer = (request.META.get("HTTP_REFERER") or "").strip()
    host = ""
    if referrer:
        try:
            host = _host(urlsplit(referrer).hostname or "")
        except ValueError:
            host = ""

    if host:
        query = _search_query(referrer)
        name = normalize_name(author_name)
        if "google" in host:
            if name and name in query:
                if "abureport" in query:
                    return SOURCE_GOOGLE_NAME_ABUREPORT
                return SOURCE_GOOGLE_NAME
            return SOURCE_GOOGLE
        if "facebook" in host or host in {"fb.com", "messenger.com"}:
            return SOURCE_FACEBOOK
        if "whatsapp" in host:
            return SOURCE_WHATSAPP
        if host in {"twitter.com", "x.com", "t.co"} or host.endswith(".twitter.com"):
            return SOURCE_X
        if "instagram" in host:
            return SOURCE_INSTAGRAM
        if "linkedin" in host:
            return SOURCE_LINKEDIN
        if "bing" in host:
            return SOURCE_BING
        if host in _own_hosts(request) or host.endswith(".abureport.com"):
            return SOURCE_ABUREPORT
        return SOURCE_OTHER

    utm_source = (request.GET.get("utm_source") or "").strip().lower()
    if not utm_source:
        return SOURCE_DIRECT
    if utm_source == SOURCE_ABUREPORT:
        return SOURCE_ABUREPORT
    if "google" in utm_source:
        return SOURCE_GOOGLE
    if "facebook" in utm_source or utm_source in {"fb", "messenger"}:
        return SOURCE_FACEBOOK
    if "whatsapp" in utm_source or utm_source == "wa":
        return SOURCE_WHATSAPP
    if utm_source in {"twitter", "x", "t.co"}:
        return SOURCE_X
    if "instagram" in utm_source:
        return SOURCE_INSTAGRAM
    if "linkedin" in utm_source:
        return SOURCE_LINKEDIN
    if "bing" in utm_source:
        return SOURCE_BING
    return SOURCE_OTHER
